// GetScenarioSteps returns the ordered progression for a specific scenario type.
func GetScenarioSteps(scenarioType model.ScenarioType) []model.SimulationStep {
	switch scenarioType {
	case model.ScenarioStealthy:
		return getStealthyScenario()
	case model.ScenarioNoisy:
		return getNoisyScenario()
	case model.ScenarioInsider:
		return getInsiderScenario()
	default:
		return getStealthyScenario()
	}
}

